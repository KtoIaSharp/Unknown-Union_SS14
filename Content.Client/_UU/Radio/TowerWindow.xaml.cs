using System;
using Content.Shared._UU.Radio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Radio;

[GenerateTypedNameReferences]
public sealed partial class TowerWindow : DefaultWindow
{
    public event Action<string, string>? OnConfigureSubmitted;

    public TowerWindow()
    {
        RobustXamlLoader.Load(this);

        // В шапке — сама вышка, как она выглядит в мире.
        DeviceView.SetPrototype("SignalTower");

        SetButton.OnPressed += _ =>
        {
            var freq = FreqInput.Text.Trim().ToUpper();
            if (string.IsNullOrWhiteSpace(freq))
                return;

            OnConfigureSubmitted?.Invoke(CodeInput.Text.Trim(), freq);
        };
    }

    public void UpdateState(TowerBuiState state)
    {
        CurrentLabel.Text = state.Frequency != null
            ? Loc.GetString("radio-current-frequency", ("freq", (object)state.Frequency))
            : Loc.GetString("radio-no-frequency");

        // Код на клиент не приходит: интерфейс знает только, заперта ли вышка.
        CodeLabel.Text = state.HasCode
            ? Loc.GetString("tower-enter-code")
            : Loc.GetString("tower-set-code");
        StatusLabel.Text = state.HasCode
            ? Loc.GetString("tower-status-locked")
            : Loc.GetString("tower-status-open");
    }
}
