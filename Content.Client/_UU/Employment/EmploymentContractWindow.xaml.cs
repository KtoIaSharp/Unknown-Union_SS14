using System;
using Content.Shared._UU.Employment;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Employment;

[GenerateTypedNameReferences]
public sealed partial class EmploymentContractWindow : DefaultWindow
{
    public event Action<string, string, string>? OnFieldsSubmitted;
    public event Action<bool, bool>? OnSignRequested;

    public EmploymentContractWindow()
    {
        RobustXamlLoader.Load(this);

        // В шапке — сам бланк договора.
        DeviceView.SetPrototype("EmploymentContract");

        ApplyButton.OnPressed += _ =>
        {
            OnFieldsSubmitted?.Invoke(
                WorkerInput.Text.Trim(),
                EmployerInput.Text.Trim(),
                PositionInput.Text.Trim());
        };

        SignEmployerButton.OnPressed += _ => OnSignRequested?.Invoke(true, false);
        SignWorkerButton.OnPressed += _ => OnSignRequested?.Invoke(false, false);
        SignStateButton.OnPressed += _ => OnSignRequested?.Invoke(true, true);
    }

    public void UpdateState(EmploymentContractBuiState state)
    {
        WorkerInput.Text = state.Worker ?? string.Empty;
        PositionInput.Text = state.Position ?? string.Empty;
        EmployerInput.Text = state.Employer ?? string.Empty;

        DateLabel.Text = string.IsNullOrWhiteSpace(state.Date)
            ? Loc.GetString("employment-contract-date-empty")
            : Loc.GetString("employment-contract-date", ("date", (object)state.Date!));

        EmployerSignLabel.Text = SignatureLine(state.EmployerSignature, state.EmployerSignatureLabel);
        WorkerSignLabel.Text = SignatureLine(state.WorkerSignature, state.WorkerSignatureLabel);

        var complete = !string.IsNullOrWhiteSpace(state.EmployerSignature)
                       && !string.IsNullOrWhiteSpace(state.WorkerSignature);

        StatusLabel.Text = Loc.GetString(complete
            ? "employment-contract-status-complete"
            : "employment-contract-status-draft");

        SignStateButton.Visible = state.CanSignAsState;
        if (state.CanSignAsState && !string.IsNullOrWhiteSpace(state.StateName))
        {
            SignStateButton.Text = Loc.GetString("employment-contract-sign-state-named",
                ("name", (object)state.StateName!));
        }
    }

    private static string SignatureLine(string? signature, string? label)
    {
        if (string.IsNullOrWhiteSpace(signature))
            return Loc.GetString("employment-contract-sign-missing");

        return Loc.GetString("employment-contract-sign-present",
            ("name", (object)(label ?? "???")));
    }
}
