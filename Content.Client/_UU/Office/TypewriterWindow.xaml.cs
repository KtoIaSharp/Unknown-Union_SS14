using System;
using System.Collections.Generic;
using System.Linq;
using Content.Shared._UU.Office;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._UU.Office;

[GenerateTypedNameReferences]
public sealed partial class TypewriterWindow : DefaultWindow
{
    public event Action<string>? OnPrintRequested;

    private readonly IPrototypeManager _prototypes;

    public TypewriterWindow()
    {
        RobustXamlLoader.Load(this);

        _prototypes = IoCManager.Resolve<IPrototypeManager>();

        // В шапке — та же машинка, что стоит в мире.
        DeviceView.SetPrototype("Typewriter");

        // До прихода состояния от сервера показываем полный список форм, но неактивным.
        PopulateForms(
            _prototypes.EnumeratePrototypes<FormPrototype>()
                .OrderBy(f => f.Order)
                .ThenBy(f => f.ID, StringComparer.Ordinal)
                .Select(f => f.ID),
            enabled: false);
    }

    public void UpdateState(TypewriterBuiState state)
    {
        StatusLabel.Text = Loc.GetString(state.HasPaper ? "typewriter-has-paper" : "typewriter-no-paper");
        PopulateForms(state.Forms, state.HasPaper);
    }

    private void PopulateForms(IEnumerable<string> formIds, bool enabled)
    {
        FormsContainer.RemoveAllChildren();

        foreach (var formId in formIds)
        {
            if (!_prototypes.TryIndex<FormPrototype>(formId, out var form))
                continue;

            // Каждая форма — карточка: название, пояснение в две строки и кнопка печати.
            var row = new PanelContainer
            {
                StyleClasses = { "PdaBorderRect" },
                HorizontalExpand = true,
            };

            var layout = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(8, 6, 8, 6),
                HorizontalExpand = true,
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                HorizontalExpand = true,
            };

            header.AddChild(new Label
            {
                Text = Loc.GetString(form.Name),
                StyleClasses = { "ConsoleText" },
                HorizontalExpand = true,
                VerticalAlignment = Control.VAlignment.Center,
            });

            var button = new Button
            {
                Text = Loc.GetString("typewriter-print"),
                StyleClasses = { "ButtonColorRed" },
                Disabled = !enabled,
                MinWidth = 96,
            };

            var id = form.ID;
            button.OnPressed += _ => OnPrintRequested?.Invoke(id);
            header.AddChild(button);
            layout.AddChild(header);

            // RichTextLabel переносит строки по доступной ширине, обычный Label — нет.
            layout.AddChild(new RichTextLabel
            {
                Text = Loc.GetString(form.Description),
                StyleClasses = { "LabelSubText" },
                MaxWidth = 400,
            });

            row.AddChild(layout);
            FormsContainer.AddChild(row);
        }
    }
}
