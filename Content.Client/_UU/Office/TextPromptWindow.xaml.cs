///     Окно ввода строки в стиле UU: заменяет стоковый QuickDialog.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TextPromptWindow : DefaultWindow
{
    public event Action<string>? OnSubmitted;
    public event Action? OnCancelled;

    private int _maxLength = 48;

    public TextPromptWindow()
    {
        RobustXamlLoader.Load(this);

        // Р’ С€Р°РїРєРµ вЂ” Р“РѕСЃСѓРґР°СЂСЃС‚РІРµРЅРЅР°СЏ Р‘СѓРјР°РіР°: Р»СЋР±РѕРµ С‚Р°РєРѕРµ РѕРєРЅРѕ СЃРІСЏР·Р°РЅРѕ СЃ РґРѕРєСѓРјРµРЅС‚Р°РјРё.
        DeviceView.SetPrototype("PaperCharter");

        // Р—РЅР°С‡РµРЅРёСЏ РїРѕ СѓРјРѕР»С‡Р°РЅРёСЋ: РѕРєРЅРѕ РѕСЃРјС‹СЃР»РµРЅРЅРѕ РІС‹РіР»СЏРґРёС‚ РµС‰С‘ РґРѕ РїСЂРёС…РѕРґР° СЃРѕСЃС‚РѕСЏРЅРёСЏ.
        Title = Loc.GetString("text-prompt-default-title");
        HeaderLabel.Text = Title;
        PromptLabel.Text = Loc.GetString("text-prompt-default-prompt");
        PlaceholderDefaults();
        SubmitButton.Text = Loc.GetString("text-prompt-submit");
        CancelButton.Text = Loc.GetString("text-prompt-cancel");

        SubmitButton.OnPressed += _ => Submit();
        CancelButton.OnPressed += _ => OnCancelled?.Invoke();

        Input.OnTextEntered += _ => Submit();
    }

    private void Submit()
    {
        var text = Input.Text;
        if (_maxLength > 0 && text.Length > _maxLength)
            text = text[.._maxLength];

        OnSubmitted?.Invoke(text);
    }

    private void PlaceholderDefaults()
    {
        Input.PlaceHolder = Loc.GetString("faction-name-placeholder");
    }

    /// <summary>Р—Р°РїРѕР»РЅСЏРµС‚ РѕРєРЅРѕ РґР°РЅРЅС‹РјРё РёР· СЃРѕСЃС‚РѕСЏРЅРёСЏ EUI.</summary>
    public void ApplyState(string title, string prompt, string placeholder, int maxLength,
        string submitLabel, string cancelLabel)
    {
        Title = title;
        HeaderLabel.Text = title;
        PromptLabel.Text = prompt;
        Input.PlaceHolder = placeholder;
        _maxLength = maxLength;
        SubmitButton.Text = submitLabel;
        CancelButton.Text = cancelLabel;
    }
}
