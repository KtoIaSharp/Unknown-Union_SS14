using System;
using System.IO;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkIdCardWindow : DefaultWindow
{
    [Dependency] private readonly IClyde _clyde = default!;

    private OwnedTexture? _photo;

    public WorkIdCardWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        DeviceView.SetPrototype("WorkIdCard");

        PhotoTexture.Visible = false;

        // Заглушки, чтобы окно не выглядело пустым до прихода состояния.
        var unknown = Loc.GetString("work-card-unknown");
        HolderLabel.Text = unknown;
        PositionLabel.Text = unknown;
        EmployerLabel.Text = unknown;
        DateLabel.Text = unknown;
        TagLabel.Text = Loc.GetString("work-card-no-tag");
        EmployerSignatureLabel.Text = Loc.GetString("work-card-unsigned");
        WorkerSignatureLabel.Text = Loc.GetString("work-card-unsigned");
        StampLabel.Text = Loc.GetString("work-card-no-stamp");
    }

    public void UpdateState(WorkIdCardBuiState state)
    {
        HolderLabel.Text = OrUnknown(state.Holder);
        PositionLabel.Text = OrUnknown(state.Position);
        EmployerLabel.Text = OrUnknown(state.Employer);
        DateLabel.Text = OrUnknown(state.Date);

        TagLabel.Text = string.IsNullOrWhiteSpace(state.Tag)
            ? Loc.GetString("work-card-no-tag")
            : state.Tag!;

        EmployerSignatureLabel.Text = string.IsNullOrWhiteSpace(state.EmployerSignatureLabel)
            ? Loc.GetString("work-card-unsigned")
            : state.EmployerSignatureLabel!;

        WorkerSignatureLabel.Text = string.IsNullOrWhiteSpace(state.WorkerSignatureLabel)
            ? Loc.GetString("work-card-unsigned")
            : state.WorkerSignatureLabel!;

        RevokedLabel.Visible = state.Revoked;

        if (state.Revoked)
        {
            RevokedLabel.Text = state.RevokedBy is { } by
                ? Loc.GetString("work-card-revoked-by", ("state", by), ("date", state.RevokedAt ?? "-"))
                : Loc.GetString("work-card-revoked");
        }
        StampLabel.Text = state.RegistryStamped
            ? Loc.GetString("work-card-stamped", ("name", state.RegistryStampFaction ?? Loc.GetString("registry-stamp-no-state")))
            : Loc.GetString("work-card-no-stamp");

        SetPhoto(state.Photo?.ImageBase64);
    }

    private void SetPhoto(string? imageBase64)
    {
        _photo?.Dispose();
        _photo = null;
        PhotoTexture.Texture = null;

        if (!string.IsNullOrEmpty(imageBase64))
        {
            try
            {
                using var stream = new MemoryStream(Convert.FromBase64String(imageBase64));
                _photo = _clyde.LoadTextureFromPNGStream(stream);
                PhotoTexture.Texture = _photo;
            }
            catch (Exception)
            {
                // Битый слепок — показываем «нет фотографии» вместо падения окна.
                _photo = null;
            }
        }

        PhotoTexture.Visible = _photo != null;
        NoPhotoLabel.Visible = _photo == null;
    }

    private static string OrUnknown(string? value)
    {
        return string.IsNullOrWhiteSpace(value) ? Loc.GetString("work-card-unknown") : value!;
    }
}
