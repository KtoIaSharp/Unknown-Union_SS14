using System;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkIdCardWindow : DefaultWindow
{
    public WorkIdCardWindow()
    {
        RobustXamlLoader.Load(this);
        DeviceView.SetPrototype("WorkIdCard");
    }

    public void UpdateState(WorkIdCardBuiState state)
    {
        HolderLabel.Text = string.IsNullOrWhiteSpace(state.Holder)
            ? Loc.GetString("work-card-unknown")
            : state.Holder!;

        PositionLabel.Text = string.IsNullOrWhiteSpace(state.Position)
            ? Loc.GetString("work-card-unknown")
            : state.Position!;

        EmployerLabel.Text = string.IsNullOrWhiteSpace(state.Employer)
            ? Loc.GetString("work-card-unknown")
            : state.Employer!;

        DateLabel.Text = string.IsNullOrWhiteSpace(state.Date)
            ? Loc.GetString("work-card-unknown")
            : state.Date!;

        WorkplaceLabel.Text = string.IsNullOrWhiteSpace(state.Workplace)
            ? Loc.GetString("work-card-unknown")
            : state.Workplace!;

        TagLabel.Text = string.IsNullOrWhiteSpace(state.Tag)
            ? Loc.GetString("work-card-no-tag")
            : state.Tag!;

        SignatureLabel.Text = string.IsNullOrWhiteSpace(state.EmployerSignatureLabel)
            ? Loc.GetString("work-card-unsigned")
            : state.EmployerSignatureLabel!;

        PhotoLabel.Text = DescribePhoto(state.Photo);
    }

    private static string DescribePhoto(PhotoSnapshot? photo)
    {
        if (photo == null)
            return Loc.GetString("work-card-no-photo");

        var parts = new[]
        {
            Loc.GetString("work-card-photo-species", ("species", photo.Species.Id)),
            photo.HairStyle ?? Loc.GetString("work-card-no-hair"),
            photo.FacialHairStyle ?? Loc.GetString("work-card-no-beard"),
        };

        return string.Join(" · ", parts);
    }
}
