using System;
using System.Collections.Generic;
using System.Linq;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkIdConsoleWindow : DefaultWindow
{
    public event Action<string, string, string, string, string?, bool>? OnApply;
    public event Action<List<string>, List<string>>? OnAccessSave;

    private WorkIdConsoleBuiState? _state;
    private WorkIdConsoleAccessWindow? _access;

    public WorkIdConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        DeviceView.SetPrototype("WorkIdConsole");

        ApplyButton.OnPressed += _ =>
        {
            // Идентификаторы пунктов списка — это индексы в state.Tags (0 — «без тега»).
            string? tag = null;
            if (_state != null && TagSelect.SelectedId > 0 && TagSelect.SelectedId <= _state.Tags.Count)
                tag = _state.Tags[TagSelect.SelectedId - 1];

            var newTag = NewTagInput.Text.Trim();
            if (!string.IsNullOrWhiteSpace(newTag))
                tag = newTag;

            OnApply?.Invoke(
                HolderInput.Text.Trim(),
                PositionInput.Text.Trim(),
                EmployerInput.Text.Trim(),
                WorkplaceInput.Text.Trim(),
                tag,
                PhotoCheck.Pressed);
        };

        AccessButton.OnPressed += _ => OpenAccess();
    }

    public void UpdateState(WorkIdConsoleBuiState state)
    {
        _state = state;

        FactionLabel.Text = string.IsNullOrWhiteSpace(state.FactionName)
            ? Loc.GetString("work-console-unbound")
            : Loc.GetString("work-console-bound-to", ("name", state.FactionName!));

        CardStatus.Text = state.HasCard
            ? Loc.GetString("work-console-card-present")
            : Loc.GetString("work-console-card-missing");

        PhotoStatus.Text = state.HasPhoto
            ? Loc.GetString("work-console-photo-present")
            : Loc.GetString("work-console-photo-missing");

        HolderInput.Text = state.Holder ?? string.Empty;
        PositionInput.Text = state.Position ?? string.Empty;
        EmployerInput.Text = state.Employer ?? string.Empty;
        WorkplaceInput.Text = state.Workplace ?? string.Empty;

        TagSelect.Clear();
        TagSelect.AddItem(Loc.GetString("work-console-tag-none"), 0);

        for (var i = 0; i < state.Tags.Count; i++)
            TagSelect.AddItem(state.Tags[i], i + 1);

        var selected = !string.IsNullOrWhiteSpace(state.Tag) && state.Tags.Contains(state.Tag!)
            ? state.Tags.IndexOf(state.Tag!) + 1
            : 0;

        TagSelect.SelectId(selected);

        AccessButton.Disabled = !state.CanEdit;
        _access?.UpdateState(state);
    }

    private void OpenAccess()
    {
        if (_state == null)
            return;

        if (_access == null)
        {
            _access = new WorkIdConsoleAccessWindow();
            _access.OnSaved += (useTags, editTags) => OnAccessSave?.Invoke(useTags, editTags);
            _access.OnClose += () => _access = null;
        }

        _access.UpdateState(_state);
        _access.OpenCentered();
    }
}
