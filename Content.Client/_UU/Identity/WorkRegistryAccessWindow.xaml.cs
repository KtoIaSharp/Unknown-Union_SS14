using System;
using System.Collections.Generic;
using System.Linq;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkRegistryAccessWindow : DefaultWindow
{
    public event Action<List<string>, List<string>>? OnSaved;

    private readonly List<(string Tag, CheckBox Use, CheckBox Edit)> _rows = new();

    public WorkRegistryAccessWindow()
    {
        RobustXamlLoader.Load(this);

        SaveButton.OnPressed += _ =>
        {
            var use = _rows.Where(r => r.Use.Pressed).Select(r => r.Tag).ToList();
            var edit = _rows.Where(r => r.Edit.Pressed).Select(r => r.Tag).ToList();
            OnSaved?.Invoke(use, edit);
        };

        CancelButton.OnPressed += _ => Close();
    }

    public void UpdateState(WorkRegistryBuiState state)
    {
        _rows.Clear();
        UseBox.RemoveAllChildren();
        EditBox.RemoveAllChildren();

        var tags = new List<string>(state.Tags);

        if (tags.Count == 0)
        {
            UseBox.AddChild(new Label
            {
                StyleClasses = { "LabelSubText" },
                Text = Loc.GetString("work-registry-access-no-tags"),
            });
            return;
        }

        foreach (var tag in tags)
        {
            var use = new CheckBox { Text = tag, Pressed = state.UseTags.Contains(tag) };
            var edit = new CheckBox { Text = tag, Pressed = state.EditTags.Contains(tag) };

            UseBox.AddChild(use);
            EditBox.AddChild(edit);
            _rows.Add((tag, use, edit));
        }
    }
}
