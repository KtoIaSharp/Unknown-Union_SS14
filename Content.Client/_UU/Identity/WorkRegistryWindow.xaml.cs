using System;
using System.Numerics;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkRegistryWindow : DefaultWindow
{
    public event Action<(string Name, string Position, string Tag, bool Revoke)>? OnRevokeRequested;
    public event Action? OnAccessRequested;

    public WorkRegistryWindow()
    {
        RobustXamlLoader.Load(this);
        DeviceView.SetPrototype("WorkRegistryConsole");

        AccessButton.OnPressed += _ => OnAccessRequested?.Invoke();
        CloseAction.OnPressed += _ => Close();
    }

    public void UpdateState(WorkRegistryBuiState state)
    {
        FactionLabel.Text = string.IsNullOrWhiteSpace(state.FactionName)
            ? Loc.GetString("work-registry-unbound-short")
            : Loc.GetString("work-registry-faction", ("name", state.FactionName!));

        SummaryLabel.Text = Loc.GetString("work-registry-summary",
            ("count", state.Entries.Count),
            ("tags", state.Tags.Count));

        AccessButton.Disabled = !state.CanEdit;

        EntriesBox.RemoveAllChildren();

        if (state.Entries.Count == 0)
        {
            EntriesBox.AddChild(new Label
            {
                StyleClasses = { "LabelSubText" },
                Text = Loc.GetString("work-registry-empty"),
            });
            return;
        }

        foreach (var entry in state.Entries)
            EntriesBox.AddChild(BuildRow(entry));
    }

    private Control BuildRow(WorkRegistryEntry entry)
    {
        var panel = new PanelContainer { StyleClasses = { "PdaBorderRect" } };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            Margin = new Thickness(6, 4),
        };

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        text.AddChild(new Label
        {
            StyleClasses = { "ConsoleText" },
            Text = $"{entry.Name} — {entry.Position}",
        });

        text.AddChild(new Label
        {
            StyleClasses = { "LabelSubText" },
            Text = Loc.GetString("work-registry-entry-details",
                ("tag", entry.Tag ?? "-"),
                ("employer", entry.Employer ?? "-"),
                ("date", entry.Date ?? "-")),
        });

        row.AddChild(text);

        var name = entry.Name;
        var position = entry.Position;
        var tag = entry.Tag ?? string.Empty;
        var revoke = !entry.Revoked;

        var action = new Button
        {
            StyleClasses = { "ButtonColorRed" },
            MinWidth = 120,
            Text = Loc.GetString(entry.Revoked ? "work-registry-restore" : "work-registry-fire"),
        };

        action.OnPressed += _ => OnRevokeRequested?.Invoke((name, position, tag, revoke));

        row.AddChild(action);
        panel.AddChild(row);
        return panel;
    }
}
