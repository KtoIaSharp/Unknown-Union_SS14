using System;
using System.Collections.Generic;
using System.Linq;
using Content.Shared._UU.Identity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._UU.Identity;

[GenerateTypedNameReferences]
public sealed partial class WorkIdConsoleAccessWindow : DefaultWindow
{
    public event Action<List<string>, List<string>>? OnSaved;

    private WorkIdConsoleBuiState? _state;

    public WorkIdConsoleAccessWindow()
    {
        RobustXamlLoader.Load(this);

        SaveButton.OnPressed += _ =>
        {
            OnSaved?.Invoke(Collect(UseColumn), Collect(EditColumn));
            Close();
        };

        CancelButton.OnPressed += _ => Close();
    }

    public void UpdateState(WorkIdConsoleBuiState state)
    {
        _state = state;

        UseColumn.RemoveAllChildren();
        EditColumn.RemoveAllChildren();

        foreach (var tag in state.Tags)
        {
            var use = new CheckBox
            {
                Text = tag,
                Pressed = state.UseTags.Contains(tag),
            };
            UseColumn.AddChild(use);

            var edit = new CheckBox
            {
                Text = tag,
                Pressed = state.EditTags.Contains(tag),
            };
            EditColumn.AddChild(edit);
        }

        if (state.Tags.Count == 0)
        {
            UseColumn.AddChild(new Label { Text = Loc.GetString("work-console-no-tags"), StyleClasses = { "LabelSubText" } });
            EditColumn.AddChild(new Label { Text = Loc.GetString("work-console-no-tags"), StyleClasses = { "LabelSubText" } });
        }
    }

    private static List<string> Collect(BoxContainer column)
    {
        return column.Children
            .OfType<CheckBox>()
            .Where(cb => cb.Pressed)
            .Select(cb => cb.Text ?? string.Empty)
            .Where(text => !string.IsNullOrWhiteSpace(text))
            .ToList();
    }
}
